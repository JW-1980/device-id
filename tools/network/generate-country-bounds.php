<?php

declare(strict_types=1);

/**
 * Regenerates src/Signals/CountryBounds.php from Natural Earth's admin-0 countries GeoJSON
 * (public domain): one bounding box per ISO 3166-1 alpha-2 code, over EVERY polygon of the
 * feature, overseas territories included (so France's box spans French Guiana and Réunion).
 * A box that large only ever makes the impossible-travel rule more cautious, never less.
 *
 *   php tools/network/generate-country-bounds.php ne_50m_admin_0_countries.geojson > src/Signals/CountryBounds.php
 *
 * The GeoJSON: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_0_countries.geojson
 */
if ($argc < 2 || ! is_file($argv[1])) {
    fwrite(STDERR, "usage: php tools/network/generate-country-bounds.php <ne_50m_admin_0_countries.geojson>\n");
    exit(2);
}

$geo = json_decode((string) file_get_contents($argv[1]), true, 512, JSON_THROW_ON_ERROR);

/** @var array<string, array{0: float, 1: float, 2: float, 3: float}> $boxes south, west, north, east */
$boxes = [];
$walk = static function (mixed $node) use (&$walk, &$min): void {
    if (is_array($node) && isset($node[0]) && is_numeric($node[0]) && isset($node[1]) && is_numeric($node[1])) {
        $min[0] = min($min[0], (float) $node[1]);
        $min[1] = min($min[1], (float) $node[0]);
        $min[2] = max($min[2], (float) $node[1]);
        $min[3] = max($min[3], (float) $node[0]);

        return;
    }
    foreach ((array) $node as $child) {
        $walk($child);
    }
};

foreach ($geo['features'] as $feature) {
    $properties = $feature['properties'];
    $code = $properties['ISO_A2_EH'] ?? $properties['ISO_A2'] ?? '-99';
    if (! is_string($code) || preg_match('/^[A-Z]{2}$/', $code) !== 1) {
        continue;
    }
    $min = [90.0, 180.0, -90.0, -180.0];
    $walk($feature['geometry']['coordinates'] ?? []);
    $boxes[$code] = [
        isset($boxes[$code]) ? min($boxes[$code][0], $min[0]) : $min[0],
        isset($boxes[$code]) ? min($boxes[$code][1], $min[1]) : $min[1],
        isset($boxes[$code]) ? max($boxes[$code][2], $min[2]) : $min[2],
        isset($boxes[$code]) ? max($boxes[$code][3], $min[3]) : $min[3],
    ];
}
ksort($boxes);

echo "<?php\n\ndeclare(strict_types=1);\n\nnamespace DeviceId\\Signals;\n\n";
echo "/**\n * Bounding boxes of the world's countries, for the impossible-travel rule. GENERATED by\n";
echo " * tools/network/generate-country-bounds.php from Natural Earth admin-0 countries 1:50m\n";
echo " * (Public Domain, https://www.naturalearthdata.com/about/terms-of-use/); do not edit by hand.\n";
echo " *\n * One box per ISO 3166-1 alpha-2 code over every polygon of the feature, overseas territories\n";
echo " * included, so a box is never smaller than the country: the distance between two boxes is a\n";
echo " * lower bound of the distance between the countries.\n */\n";
echo "final class CountryBounds\n{\n";
echo "    /** @var array<string, array{0: float, 1: float, 2: float, 3: float}> south, west, north, east (degrees) */\n";
echo "    public const BOXES = [\n";
foreach ($boxes as $code => [$s, $w, $n, $e]) {
    printf("        '%s' => [%s, %s, %s, %s],\n", $code, round($s, 2), round($w, 2), round($n, 2), round($e, 2));
}
echo "    ];\n}\n";
